#!/usr/bin/env node
// Generates SQL for the territory areas in supabase/seed/areas.json (PRD territory leaderboards).
//   node scripts/db/seed-areas.mjs > supabase/seed/areas.sql
// Each area gets its boundary (MultiPolygon) and its res 11 H3 tiles (cells whose centre is inside).
// Upserts, so re-running after editing areas.json updates names, boundaries and tiles.
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { polygonToCells } from "h3-js";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const { areas, attribution } = JSON.parse(readFileSync(join(root, "supabase/seed/areas.json"), "utf8"));
const s = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);

const out = [`-- Generated by scripts/db/seed-areas.mjs on ${new Date().toISOString()}. ${attribution}.`, "begin;"];
for (const a of areas) {
  // polygons: [polygon][ring][[lng, lat]]; h3-js wants [lng, lat] with isGeoJson = true.
  const cells = new Set(a.polygons.flatMap((poly) => polygonToCells(poly, 11, true)));
  const wkt = `MULTIPOLYGON(${a.polygons.map((poly) => `(${poly.map((ring) => `(${ring.map(([x, y]) => `${x} ${y}`).join(",")})`).join(",")})`).join(",")})`;
  out.push(`insert into public.areas (id, name, kind, boundary, total_tiles, source)
values (${s(a.id)}, ${s(a.name)}, ${s(a.kind)}, extensions.st_geogfromtext(${s("SRID=4326;" + wkt)}), ${cells.size}, ${s(a.source)})
on conflict (id) do update set name = excluded.name, kind = excluded.kind, boundary = excluded.boundary,
  total_tiles = excluded.total_tiles, source = excluded.source;
delete from public.area_tiles where area_id = ${s(a.id)};
insert into public.area_tiles (area_id, h3) values
${[...cells].map((c) => `  (${s(a.id)}, ${BigInt("0x" + c)})`).join(",\n")};`);
  console.error(`${a.id}: ${cells.size} tiles`);
}
out.push("commit;");
console.log(out.join("\n\n"));
